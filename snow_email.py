def section(title, content):
    """Email section with a header line."""
    return (f'<h3 style="{FONT}font-size:16px;color:#111;margin:20px 0 8px;padding-bottom:4px;'
            f'border-bottom:1px solid #ddd;">{title}</h3>{content}')


def get_touring(cfg):
    """Return (html, text) for the AI touring outlook, or ("", "") if it's off or fails."""
    model = (cfg.get("touring") or {}).get("model")
    if not model:
        return "", ""
    try:
        import touring_prompt
        text = touring_prompt.ask_claude(touring_prompt.build_prompt(cfg), model)
    except Exception as e:
        print(f"Touring outlook failed: {e}", flush=True)
        return "", ""
    # Keep only the message inside <message> tags, dropping any notes the model adds around it
    m = re.search(r"<message>(.*?)(?:</message>|$)", text, re.S)
    text = (m[1] if m else text).strip()
    if UAC_LINE not in text:
        text += "\n\n" + UAC_LINE
    # **bold** from the model -> <b> in HTML; markers stripped in the plain-text email
    bold = lambda s: re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", html.escape(s))
    out, bullets, first = [], [], True

    def flush():
        if bullets:
            out.append(f'<ul style="{FONT}font-size:14px;color:#222;line-height:1.45;margin:4px 0;'
                       'padding-left:20px;">' + "".join(f"<li>{bold(b)}</li>" for b in bullets)
                       + "</ul>")
            bullets.clear()

    # Walk line by line so bullets and paragraphs keep the model's order
    for line in (ln.strip() for ln in text.splitlines()):
        if not line:
            flush()
        elif line.startswith(("- ", "* ")):
            bullets.append(line[2:])
        else:
            flush()
            size, color = "14px", "#222"
            if first:
                size, color, first = "15px;font-weight:bold", "#111", False
            elif line.startswith("This is a weather-based outlook"):
                size, color = "11px", "#888"
            out.append(f'<p style="{FONT}font-size:{size};color:{color};line-height:1.45;'
                       f'margin:8px 0;">{bold(line)}</p>')
    flush()
    return "".join(out), text.replace("**", "")


def fetch(url):
    r = requests.get(url, headers=UA, timeout=60)
    r.raise_for_status()
    return r.text


def to_float(s):
    try:
        return float(s)
    except ValueError:
        return float("nan")


def parse(html):
    """Return (init datetime or None, (lat, lon, elev ft) or None, {table title: {row: [values]}})."""
    soup = BeautifulSoup(html, "html.parser")
    text = " ".join(soup.get_text(" ").split())
    m = INIT_RE.search(text)
    init = None
    if m:
        init = datetime.strptime(f"{m[1]}{m[2]} {m[3]}", "%H%M %d %b %Y")
        init = init.replace(tzinfo=timezone.utc)
    p = POINT_RE.search(text)
    point = (float(p[1]), -float(p[2]), int(p[3])) if p else None

    tables = {}
    for t in soup.find_all("table"):
        title = t.find_previous(string=re.compile("Guidance"))
        if not title:
            continue
        rows = {}
        for tr in t.find_all("tr"):
            cells = [c.get_text(strip=True) for c in tr.find_all(["td", "th"])]
            if cells and cells[0] in ROW_LABELS:
                rows[cells[0]] = [to_float(x) for x in cells[1:]]
        if rows:
            tables[" ".join(title.split())] = rows
    return init, point, tables


def temps_open_meteo(lat, lon, elev_ft):
    """{local date: (high, low)} in °F for 10 days."""
    r = requests.get("https://api.open-meteo.com/v1/forecast", headers=UA, timeout=30, params={
        "latitude": lat, "longitude": lon, "elevation": round(elev_ft * 0.3048),
        "daily": "temperature_2m_max,temperature_2m_min", "temperature_unit": "fahrenheit",
        "timezone": "America/Denver", "forecast_days": CHART_DAYS + 1,
    })
    r.raise_for_status()
    d = r.json()["daily"]
    return {datetime.fromisoformat(t).date(): (hi, lo)
            for t, hi, lo in zip(d["time"], d["temperature_2m_max"], d["temperature_2m_min"])
            if hi is not None and lo is not None}


def temps_nws(lat, lon):
    """{local date: (high, low)} in °F from NWS hourly forecast (about 7 days)."""
    r = requests.get("https://forecast.weather.gov/MapClick.php", headers=UA, timeout=30,
                     params={"lat": lat, "lon": lon, "FcstType": "digitalDWML"})
    r.raise_for_status()
    root = ET.fromstring(r.content)
    times = [datetime.fromisoformat(t.text).astimezone(LOCAL_TZ).date()
             for t in root.find(".//time-layout").iter("start-valid-time")]
    vals = [v.text for v in root.find(".//temperature[@type='hourly']").iter("value")]
    by_day = {}
    for day, v in zip(times, vals):
        if v and v.strip():
            by_day.setdefault(day, []).append(float(v))
    # Skip days with too few hours for a fair high/low (e.g. the tail of the forecast).
    return {d: (max(v), min(v)) for d, v in by_day.items() if len(v) >= 18}


HRRR_FILE_RE = re.compile(r'href="(hrrrlccforecast_(\d{10})\.txt)"')
HRRR_ROW_RE = re.compile(
    r"^\s*\d+\s+(\d{2} [AP]M \w{3} \w{3} \d{1,2} \d{4})\s+(\S+)\s+(\S+)\s+(\S+)"
    r"\s+(-?\d+)F\s+(-?\d+)F\s+(-?\d+)F\s+-?\d+F\s+-?\d+F\s+\S+\s+(\d+):1/\s*\S*"
    r"\s+([\d.]+)/\s*[\d.]+\s+([\d.]+)/\s*[\d.]+\s*$")
WIND_RE = re.compile(r"([NSEW]+)(\d+)(?:G(\d+))?")


def hrrr_hourly(base_url):
    """Hourly CLN forecast from the newest HRRR text file, as (init label, [rows]).

    Each row: {time, temp, wind_dir, wind, gust, slr, water, snow}. Winds are from
    Top of Collins (ALT); CLN has no wind column. Past hours are dropped.
    """
    files = sorted(HRRR_FILE_RE.findall(fetch(base_url)), key=lambda f: f[1])
    if not files:
        raise ValueError("no HRRR files listed")
    now = datetime.now(LOCAL_TZ)
    for name, stamp in reversed(files[-2:]):  # newest, then the one before
        rows = []
        for line in fetch(base_url + name).splitlines():
            m = HRRR_ROW_RE.match(line)
            if not m:
                continue
            t = datetime.strptime(m[1], "%I %p %a %b %d %Y").replace(tzinfo=LOCAL_TZ)
            w = WIND_RE.fullmatch(m[3])  # ALT wind
            rows.append({
                "time": t, "temp": int(m[7]),
                "wind_dir": w[1] if w else "", "wind": int(w[2]) if w else 0,
                "gust": int(w[3]) if w and w[3] else None,
                "slr": int(m[8]), "water": float(m[9]), "snow": float(m[10]),
            })
        rows = [r for r in rows if r["time"] > now]
        if rows:
            return f"{stamp[8:]}Z {stamp[6:8]}/{stamp[4:6]}", rows
    raise ValueError("HRRR files had no future hours")


def nws_precip_chance(lat, lon):
    """{hour start (local): (chance %, 'snow'|'rain'|'')} from the NWS hourly forecast."""
    r = requests.get("https://forecast.weather.gov/MapClick.php", headers=UA, timeout=30,
                     params={"lat": lat, "lon": lon, "FcstType": "digitalDWML"})
    r.raise_for_status()
    root = ET.fromstring(r.content)
    times = [datetime.fromisoformat(t.text).astimezone(LOCAL_TZ)
             for t in root.find(".//time-layout").iter("start-valid-time")]
    pops = [v.text for v in root.find(".//probability-of-precipitation").iter("value")]
    kinds = []
    for c in root.find(".//weather").iter("weather-conditions"):
        types = " ".join(v.get("weather-type", "") for v in c.iter("value"))
        kinds.append("snow" if "snow" in types else "rain" if "rain" in types else "")
    out = {}
    for i, t in enumerate(times):
        if i < len(pops) and pops[i]:
            out[t] = (int(pops[i]), kinds[i] if i < len(kinds) else "")
    return out


def hourly_html(init_label, rows, chances, layout="blocks"):
    """Hourly forecast table.

    layout "blocks": stacked 12-hour tables (6a-5p, 6p-5a) that fit a phone screen.
    layout "scroll": one wide table in a sideways-scrolling box, labels pinned on the left.
    """
    cell = ("text-align:center;padding:2px 1px;font-family:Arial,sans-serif;"
            "font-size:11px;width:23px;min-width:23px;white-space:nowrap;color:#222;")
    label = ("text-align:left;padding:2px 4px 2px 0;font-family:Arial,sans-serif;"
             "font-size:11px;color:#666;white-space:nowrap;")
    top = max((r["snow"] for r in rows), default=0)  # same bar scale in every block
    on, off = "color:#1d4ed8;font-weight:bold;", "color:#bbb;"

    def hr(t):
        return f'{t.hour % 12 or 12}{"a" if t.hour < 12 else "p"}'

    def block(rs, scroll=False):
        cols = {k: [] for k in ("hour", "bar", "snow", "water", "slr", "temp", "dir",
                                "wind", "gust", "pop")}
        for i, r in enumerate(rs):
            e = "border-left:1px solid #ccc;" if i and r["time"].hour == 0 else ""  # midnight
            td = f'<td style="{cell}{e}'
            cols["hour"].append(f'{td}color:#666;">{hr(r["time"])}</td>')
            bh = 0 if top <= 0 or r["snow"] <= 0 else max(round(r["snow"] / top * 30), 2)
            bar = (f'<div style="width:14px;height:{bh}px;background:#3b82f6;margin:0 auto;'
                   f'border-radius:2px 2px 0 0;"></div>') if bh else ""
            cols["bar"].append(f'<td height="30" style="{cell}{e}height:30px;vertical-align:bottom;'
                               f'border-bottom:1px solid #ccc;">{bar}</td>')
            cols["snow"].append(f'{td}{on if r["snow"] else off}">{r["snow"]:.1f}</td>')
            cols["water"].append(f'{td}{on if r["water"] else off}">{r["water"]:.2f}</td>')
            # 0:1 means no precip that hour, so leave it blank
            ratio = f'{r["slr"]}:1' if r["slr"] else ""
            cols["slr"].append(f'{td}">{ratio}</td>')
            cols["temp"].append(f'{td}">{r["temp"]}&deg;</td>')
            cols["dir"].append(f'{td}">{r["wind_dir"]}</td>')
            cols["wind"].append(f'{td}">{r["wind"]}</td>')
            cols["gust"].append(f'{td}">{r["gust"] or ""}</td>')
            # NWS hours are labelled by start; HRRR hours by end.
            c = chances.get(r["time"] - timedelta(hours=1))
            cols["pop"].append(f'{td}">{"" if c is None else c[0]}</td>')
        names = {"hour": "", "bar": "", "snow": "Snow", "water": "H2O", "slr": "SLR",
                 "temp": "Temp", "dir": "Dir", "wind": "Wind", "gust": "Gust", "pop": "Chance"}
        # In scroll mode the labels stay put while the hours slide under them
        lab = label + ("position:sticky;left:0;background:#fff;z-index:1;" if scroll else "")
        body = "".join(f'<tr><td style="{lab}">{names[k]}</td>{"".join(v)}</tr>'
                       for k, v in cols.items())
        if scroll:
            days, start = [], 0
            for i in range(1, len(rs) + 1):
                if i == len(rs) or rs[i]["time"].date() != rs[start]["time"].date():
                    d = rs[start]["time"]
                    e = "border-left:1px solid #ccc;" if start else ""
                    days.append(f'<td colspan="{i - start}" style="{cell}{e}text-align:left;'
                                f'font-weight:bold;padding-left:3px;">{d:%a} {d.day}</td>')
                    start = i
            body = f'<tr><td style="{lab}"></td>{"".join(days)}</tr>' + body
            return ('<div style="overflow-x:auto;overflow-y:hidden;padding-bottom:14px;'
                    '-webkit-overflow-scrolling:touch;width:100%;'
                    'max-width:calc(100vw - 16px);display:block;">'
                    '<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;">'
                    f'{body}</table></div>')
        a, b = rs[0]["time"], rs[-1]["time"]
        end = hr(b) if a.date() == b.date() else f"{b:%a} {b.day} {hr(b)}"
        head = (f'<p style="font-family:Arial,sans-serif;font-size:12px;font-weight:bold;'
                f'color:#222;margin:10px 0 2px;">{a:%a} {a.day} {hr(a)} &ndash; {end}</p>')
        return (head + '<table cellpadding="0" cellspacing="0" '
                f'style="border-collapse:collapse;">{body}</table>')

    # Start a new block at each 6 am and 6 pm
    blocks, cur = [], []
    for r in rows:
        if cur and r["time"].hour in (6, 18):
            blocks.append(cur)
            cur = []
        cur.append(r)
    if cur:
        blocks.append(cur)

    tot_s, tot_w = sum(r["snow"] for r in rows), sum(r["water"] for r in rows)
    title = (f'<p style="font-family:Arial,sans-serif;font-size:13px;margin:12px 0 4px;">'
             f'<b>Next {len(rows)} hours at Collins</b>: {tot_s:.1f}" snow, {tot_w:.2f}" water '
             f'<span style="color:#888;">(HRRR {init_label})</span></p>')
    note = ('<p style="font-family:Arial,sans-serif;font-size:11px;color:#888;margin:6px 0 16px;">'
            'Snow and H2O (water) in inches; SLR = snow-to-liquid ratio; wind and gusts in mph '
            'from Top of Collins (ALT); chance of precip (%) from NWS.</p>')
    if layout == "scroll":
        tables = block(rows, scroll=True)
        note = note.replace("from NWS.", "from NWS. Swipe sideways for more hours.")
    else:
        tables = "".join(block(b) for b in blocks)
    return title + tables + note, tot_s, tot_w


def get_hourly(loc, point):
    """Return (html, text line) for the 48-h table, or ("", "") if it can't be built."""
    base = loc.get("hourly_dir")
    if not base:
        return "", ""
    try:
        init_label, rows = hrrr_hourly(base)
    except Exception as e:
        print(f"Hourly HRRR forecast failed: {e}", flush=True)
        return "", ""
    chances = {}
    if point:
        try:
            chances = nws_precip_chance(point[0], point[1])
        except Exception as e:
            print(f"NWS precip chance failed: {e}", flush=True)
    html_part, s, w = hourly_html(init_label, rows, chances, loc.get("hourly_layout", "blocks"))
    return html_part, f"Next {len(rows)} h (HRRR {init_label}): {s:.1f} in snow, {w:.2f} in water"


def get_lake_effect():
    """Return (html, text line) for the Great Salt Lake-effect section, or ("", "") on failure."""
    try:
        run, init, clim, rows = lake_effect.parse(fetch(lake_effect.URL))
    except Exception as e:
        print(f"Lake-effect forecast failed: {e}", flush=True)
        return "", ""
    wins, hidden = lake_effect.select(lake_effect.windows(rows), init)
    if wins:
        txt = "; ".join(f"{w['start']}-{w['end']} peak {w['peak']}%" for w in wins)
    else:
        txt = "no signal"
    return lake_effect.render_html(run, clim, wins, hidden, title=False), f"Lake effect ({run}): {txt}"


def get_temps(point):
    """Return ({date: (high, low)}, source name); empty if every source fails."""
    if not point:
        return {}, None
    lat, lon, elev = point
    for name, fn in (("Open-Meteo.com", lambda: temps_open_meteo(lat, lon, elev)),
                     ("NWS", lambda: temps_nws(lat, lon))):
        try:
            temps = fn()
            if temps:
                return temps, name
        except Exception as e:
            print(f"Temperatures from {name} failed: {e}", flush=True)
    return {}, None


def find_table(tables, key):
    for title, rows in tables.items():
        if key in title:
            return rows
    raise KeyError(f"no table matching '{key}'")


def value_at(series, hours):
    i = min(hours // STEP_H - 1, len(series) - 1)
    return series[max(i, 0)]


def daily_snow(total, init):
    """Snow per day as [(local date, inches)], 00Z to 00Z (6 pm MDT / 5 pm MST).

    Taken as differences of the cumulative series; partial first days are dropped.
    """
    days, prev, prev_end = [], 0.0, init
    for i, v in enumerate(total):
        end = init + timedelta(hours=STEP_H * (i + 1))
        if end.hour != 0:
            continue
        if end - prev_end == timedelta(hours=24) and v == v and prev == prev:  # skip NaN
            days.append((end.astimezone(LOCAL_TZ).date(), max(v - prev, 0.0)))
        prev, prev_end = v, end
        if len(days) == CHART_DAYS:
            break
    return days


def fmt_in(v):
    if v == 0:
        return '0"'
    return f'{v:.1f}"' if v < 1 else f'{v:.0f}"'


def chart_html(days, temps=None):
    """OpenSnow-style daily bar chart as an email-safe HTML table (no SVG/JS)."""
    if not days:
        return "<p>Daily chart not available.</p>"
    temps = temps or {}
    top = max(v for _, v in days)
    cell = "text-align:center;padding:0 5px;font-family:Arial,sans-serif;"
    amt, bars, dow, dom, his, los = [], [], [], [], [], []
    for d, v in days:
        h = 0 if top <= 0 or v <= 0 else max(round(v / top * BAR_PX), 2)
        bar = (f'<div style="width:22px;height:{h}px;background:#3b82f6;'
               f'margin:0 auto;border-radius:3px 3px 0 0;"></div>') if h else ""
        amt.append(f'<td style="{cell}font-size:12px;color:#333;">{fmt_in(v)}</td>')
        bars.append(f'<td height="{BAR_PX}" style="{cell}height:{BAR_PX}px;'
                    f'vertical-align:bottom;border-bottom:1px solid #ccc;">{bar}</td>')
        dow.append(f'<td style="{cell}font-size:12px;color:#666;padding-top:4px;">'
                   f'{"MTWTFSS"[d.weekday()]}</td>')
        dom.append(f'<td style="{cell}font-size:14px;font-weight:bold;color:#222;">{d.day}</td>')
        hi, lo = (f"{t:.0f}&deg;" for t in temps[d]) if d in temps else ("", "")
        his.append(f'<td style="{cell}font-size:12px;color:#c2410c;padding-top:4px;">{hi}</td>')
        los.append(f'<td style="{cell}font-size:12px;color:#2563eb;">{lo}</td>')
    shown = (amt, bars, dow, dom, his, los) if temps else (amt, bars, dow, dom)
    rows = "".join(f"<tr>{''.join(r)}</tr>" for r in shown)
    return f'<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;">{rows}</table>'


def summarize(loc, cfg):
    init, point, tables = parse(fetch(loc["url"]))
    snow = find_table(tables, "Total Snowfall")
    pcts = cfg["percentiles"]

    lines = [loc["name"]]
    run = init.strftime("%HZ %d %b %Y") if init else "unknown"
    lines.append(f"Run: {run}")
    if init:
        age = (datetime.now(timezone.utc) - init).total_seconds() / 3600
        if age > cfg["max_age_hours"]:
            lines.append(f"WARNING: run is {age:.0f} h old (page not updated)")

    if len(pcts) > 1:
        lines.append(f"{'':8}" + "".join(f"{p:>7}" for p in pcts))
    medians = {}
    for w in cfg["windows"]:
        vals = [value_at(snow[p], w["hours"]) for p in pcts]
        lines.append(f"{w['label']:8}" + "".join(f"{v:>7.1f}" for v in vals))
        medians[w["label"]] = vals[0]
    lines.append("Snowfall in inches, accumulated from model init.")

    days = daily_snow(snow[pcts[0]], init) if init else []
    if point and loc.get("temp_elevation_ft"):
        point = (point[0], point[1], loc["temp_elevation_ft"])
    temps, temp_src = get_temps(point) if days else ({}, None)
    if days:
        def day_txt(d, v):
            t = f" {temps[d][0]:.0f}/{temps[d][1]:.0f}F" if d in temps else ""
            return f"{d:%a} {d.day} {v:.1f}{t}"
        lines.append(f"Daily {pcts[0]}: " + " | ".join(day_txt(d, v) for d, v in days))
    if temp_src:
        lines.append(f"High/low temperatures (F): {temp_src}")
    hourly, hourly_txt = get_hourly(loc, point)
    if hourly_txt:
        lines.append(hourly_txt)
    lake, lake_txt = get_lake_effect() if loc.get("lake_effect") else ("", "")
    if lake_txt:
        lines.append(lake_txt)

    # HTML version: three sections
    p = f'<p style="{FONT}font-size:13px;color:#222;margin:4px 0;">'
    small = f'<p style="{FONT}font-size:11px;color:#888;margin:6px 0;">'
    td = f'style="{FONT}font-size:14px;padding:2px 16px 2px 0;'
    head = "".join(f'<td {td}color:#666;text-align:right;">{x}</td>' for x in pcts)
    trs = f'<tr><td {td}"></td>{head}</tr>' if len(pcts) > 1 else ""
    for w in cfg["windows"]:
        vals = "".join(f'<td {td}text-align:right;font-weight:bold;">{value_at(snow[x], w["hours"]):.1f}"</td>'
                       for x in pcts)
        trs += f'<tr><td {td}color:#444;">{w["label"]}</td>{vals}</tr>'
    summary = f"{p}Model run: {run}</p>"
    if init and age > cfg["max_age_hours"]:
        summary += f'{p}<b style="color:#b91c1c;">Warning: run is {age:.0f} h old (page not updated)</b></p>'
    summary += (f'<table cellpadding="0" cellspacing="0" style="margin:6px 0;">{trs}</table>'
                f"{small}Snowfall in inches, accumulated from model run.</p>")
    html_out = f'<h2 style="{FONT}font-size:20px;color:#111;margin:8px 0 0;">{html.escape(loc["name"])}</h2>'
    html_out += section("Snow Summary", summary)
    if hourly:
        html_out += section("Hourly Forecast", hourly)
    if lake:
        html_out += section("Great Salt Lake Effect", lake)
    ten_day = chart_html(days, temps)
    if temp_src:
        ten_day += f"{small}High/low temperatures (&deg;F): {temp_src}.</p>"
    html_out += section("10 Day Forecast", ten_day)
    return "\n".join(lines), medians, html_out


def send(subject, body, html_body):
    # One email per recipient so nobody sees the rest of the list.
    recipients = [a.strip() for a in os.environ["EMAIL_TO"].split(",") if a.strip()]
    host = os.environ.get("SMTP_HOST", "smtp.gmail.com")
    port = int(os.environ.get("SMTP_PORT", "465"))
    with smtplib.SMTP_SSL(host, port) as s:
        s.login(os.environ["SMTP_USER"], os.environ["SMTP_PASS"])
        for to in recipients:
            msg = EmailMessage()
            msg["Subject"] = subject
            msg["From"] = os.environ["SMTP_USER"]
            msg["To"] = to
            msg.set_content(body)
            msg.add_alternative(html_body, subtype="html")
            s.send_message(msg)


def try_all(locs, cfg):
    """Return ({name: (text, medians, chart html)}, {name: error})."""
    ok, bad = {}, {}
    for loc in locs:
        try:
            ok[loc["name"]] = summarize(loc, cfg)
        except Exception as e:
            bad[loc["name"]] = str(e)
    return ok, bad


def main():
    cfg_path = Path(os.environ.get("SNOW_CONFIG", Path(__file__).with_name("config.yaml")))
    cfg = yaml.safe_load(cfg_path.read_text())
    locs = cfg["locations"]
    delay = float(os.environ.get("RETRY_DELAY_MIN", cfg.get("retry_delay_min", 60)))

    ok, bad = try_all(locs, cfg)
    if bad and delay > 0:
        print(f"Failed: {bad}; retrying in {delay:.0f} min", flush=True)
        time.sleep(delay * 60)
        ok2, bad = try_all([l for l in locs if l["name"] in bad], cfg)
        ok.update(ok2)

    today = datetime.now(ZoneInfo("America/Denver"))
    d = today.day
    suffix = "th" if 11 <= d <= 13 else {1: "st", 2: "nd", 3: "rd"}.get(d % 10, "th")
    sections, html_parts = [], []
    subject = f"Snow forecast for {today:%a %b} {d}{suffix}"
    for loc in locs:
        name = loc["name"]
        if name in ok:
            text, _, chart = ok[name]
        else:
            text = f"{name}\nData not available (tried twice): {bad[name]}"
            chart = (f'<h2 style="{FONT}font-size:20px;margin:8px 0 0;">{html.escape(name)}</h2>'
                     f'<p style="{FONT}font-size:13px;">Data not available (tried twice): '
                     f'{html.escape(bad[name])}</p>')
        sections.append(text)
        html_parts.append(chart)

    # AI touring outlook goes last, always followed by a fixed AI disclaimer
    touring_html, touring_txt = get_touring(cfg)
    if touring_html:
        sections.append("Touring Outlook\n" + touring_txt + "\n\n" + AI_DISCLAIMER)
        html_parts.append(section("Touring Outlook", touring_html)
                          + f'<p style="{FONT}font-size:12px;color:#666;font-style:italic;'
                          f'margin:10px 0;">{html.escape(AI_DISCLAIMER)}</p>')

    if not ok:
        subject += ": data not available"
    elif len(locs) == 1:
        med = ok[locs[0]["name"]][1]
        subject += ": " + " | ".join(f'{k} {v:.0f}"' for k, v in med.items())

    source = ("Sources: Utah Snow Ensemble (U of Utah, experimental). "
              "Hourly: U of Utah HRRR guidance (experimental) and NWS. "
              "Lake effect: U of Utah GSLE guidance (GFS).")
    invite = "Share the love! Reply with a friend's email to add them to the mailing list."
    body = "\n\n".join(sections) + f"\n\n{source}\n{invite}\n"
    # Viewport + Apple tag stop iPhone Mail from shrinking the email to fit wide content.
    html_body = ('<html><head><meta name="viewport" content="width=device-width, '
                 'initial-scale=1"><meta name="x-apple-disable-message-reformatting">'
                 f'</head><body style="margin:0;padding:8px;{FONT}">' + "<br>".join(html_parts)
                 + f'<p style="{FONT}font-size:11px;color:#888;margin-top:20px;">{source}</p>'
                 + f'<p style="{FONT}font-size:14px;color:#cc0000;">{invite}</p>'
                 "</body></html>")
    if os.environ.get("DRY_RUN"):
        print(subject + "\n\n" + body)
        Path("preview.html").write_text(html_body)
        print("HTML written to preview.html")
    else:
        send(subject, body, html_body)
    if bad:
        print(f"Failed: {bad}", flush=True)
    if not ok:
        sys.exit(1)  # flag the Actions run red


if __name__ == "__main__":
    main()
